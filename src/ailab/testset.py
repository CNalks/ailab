def accepted(cases: list[Case]) -> list[Case]:
    return [c for c in cases if c.expect == "accept"]


# ---------------------------------------------------------------------------------------
def write_testset(out: Path, cases: list[Case] | None = None) -> list[Path]:
    """Write one ``<case_id>.json`` per case, ``manifest.json`` and the small FluView CSV."""
    cases = cases or build_cases()
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for c in cases:
        p = out / f"{c.case_id}.json"
        p.write_bytes(c.raw() + b"\n")
        written.append(p)
    manifest = {
        "about": "Generated by `ailab synth testset`; do not edit. POST each file's body to "
        "/api/v1/series (header X-API-Key). 'expect' is the required outcome.",
        "cases": [c.manifest_entry() for c in cases],
    }
    mp = out / "manifest.json"
    mp.write_text(json.dumps(manifest, ensure_ascii=False, indent=1) + "\n")
    written.append(mp)
    fv = next(c for c in cases if c.case_id == "fluview_wili_3y")
    csv = out.parent / "fluview_nat_small.csv"
    pd.DataFrame(fv.body["observations"]).rename(
        columns={"ds": "period_start", "y": "wili_percent"}
    ).to_csv(csv, index=False)
    written.append(csv)
    return written


def read_testset(directory: Path) -> list[Case]:
    directory = Path(directory)
    manifest = json.loads((directory / "manifest.json").read_text())
    out = []
    for e in manifest["cases"]:
        body = json.loads((directory / e["file"]).read_text())  # accepts NaN / Infinity
        out.append(
            Case(
                e["case_id"],
                e["description"],
                body,
                e["expect"],
                e["reject_contains"],
                e["tags"],
                e["expect_policy"],
            )
        )
    return out


def load_into_service(
    base_url: str,
    api_key: str,
    cases: list[Case] | None = None,
    overwrite: bool = True,
    derive: bool = True,
    timeout: float = 60.0,
) -> list[dict]:
    """POST every case to a running service through the REST API and compare with the expectation.

    Returns one result dict per case: ``{case_id, expect, status, ok, detail}``. With ``derive``
    the pair ``ts_pair_positives / ts_pair_tests`` is also turned into ``ts_pair_positivity``.
    """
    cases = cases or build_cases()
    base = base_url.rstrip("/")
    headers = {"X-API-Key": api_key, "Content-Type": "application/json"}
    results = []
    with httpx.Client(timeout=timeout) as c:
        for case in cases:
            r = c.post(
                f"{base}/api/v1/series",
                params={"overwrite": str(overwrite).lower()},
                content=case.raw(),
                headers=headers,
            )
            want = 201 if case.expect == "accept" else (400, 422)
            ok = r.status_code == want if isinstance(want, int) else r.status_code in want
            detail = ""
            if not ok or case.expect == "reject":
                try:
                    detail = json.dumps(r.json().get("error", r.json()))[:200]
                except Exception:
                    detail = r.text[:200]
            results.append(
                {
                    "case_id": case.case_id,
                    "expect": case.expect,
                    "status": r.status_code,
                    "ok": ok,
                    "detail": detail,
                }
            )
        if derive:
            r = c.post(
                f"{base}/api/v1/derive",
                json={
                    "series_id": f"{ID_PREFIX}pair_positivity",
                    "name": "Positivity (positives / tests)",
                    "expr": f"{ID_PREFIX}pair_positives / {ID_PREFIX}pair_tests",
                    "overwrite": True,
                },
                headers=headers,
            )
            results.append(
                {
                    "case_id": "derive_positivity",
                    "expect": "accept",
                    "status": r.status_code,
                    "ok": r.status_code == 201,
                    "detail": "" if r.status_code == 201 else r.text[:200],
                }
            )
    return results
